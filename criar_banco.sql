-- ---------------------------------------------------------------------
-- PARTE 1: TABELAS
-- ---------------------------------------------------------------------

CREATE TABLE tbl_pessoa (
    cp_id_pessoa      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nm_pessoa         VARCHAR(200) NOT NULL,
    email_principal   VARCHAR(254) NOT NULL,
    cd_orcid          VARCHAR(19),
    pais_pessoa       CHAR(2) NOT NULL
);

CREATE TABLE tbl_instituicao (
    cp_id_instituicao     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nm_instituicao        VARCHAR(200) NOT NULL,
    sg_instituicao        VARCHAR(30),
    pais_instituicao      CHAR(2) NOT NULL,
    cidade_instituicao    VARCHAR(100),
    uf_instituicao        CHAR(2)
);

-- Era uma tabela só com o id; agora é a associação pessoa x instituição no tempo
CREATE TABLE tbl_vinculo_institucional (
    cp_id_vinculo     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ce_pessoa         BIGINT NOT NULL,
    ce_instituicao    BIGINT NOT NULL,
    dt_inicio         DATE NOT NULL,
    dt_fim            DATE
);

CREATE TABLE tbl_evento (
    cp_id_evento   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sg_evento      VARCHAR(20) NOT NULL,
    nm_evento      VARCHAR(200) NOT NULL,
    ds_evento      VARCHAR(1000)
);

CREATE TABLE tbl_edicao (
    cp_id_edicao   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ce_evento      BIGINT NOT NULL,
    nr_edicao      INTEGER,
    ano_edicao     SMALLINT NOT NULL,
    dt_inicio      DATE NOT NULL,
    dt_fim         DATE NOT NULL
);

-- Associativa edição x pessoa (N:M)
CREATE TABLE tabela_imp_se_inscreve (
    ce_edicao      BIGINT NOT NULL,
    ce_pessoa      BIGINT NOT NULL
);

CREATE TABLE tbl_trilha (
    cp_id_trilha            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ce_edicao               BIGINT NOT NULL,
    nm_trilha               VARCHAR(150) NOT NULL,
    ds_trilha               VARCHAR(1000),
    tp_anonimato            VARCHAR(50) NOT NULL,
    nr_revisores_desejado   SMALLINT NOT NULL,
    dt_fim_registro         DATE,
    dt_fim_submissoes       DATE NOT NULL,
    dt_fim_revisoes         DATE,
    dt_fim_replica          DATE,
    dt_fim_decisao          DATE,
    dt_fim_versao_final     DATE
);

-- Participação de uma pessoa no Comitê de uma trilha (papel contextual)
CREATE TABLE tbl_comite (
    cp_id_comite   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ce_trilha      BIGINT NOT NULL,
    ce_pessoa      BIGINT NOT NULL,
    dt_inicio      DATE NOT NULL,
    dt_fim         DATE,
    funcao         VARCHAR(100) NOT NULL,
    situacao       VARCHAR(50) NOT NULL
);

-- Substitui "artigo": o trabalho é a própria submissão
CREATE TABLE tbl_submissao (
    cp_id_submissao     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ce_trilha           BIGINT NOT NULL,
    titulo_submissao    VARCHAR(500) NOT NULL,
    resumo_submissao    VARCHAR(2000) NOT NULL,
    idioma_submissao    CHAR(2) NOT NULL,
    dt_registro         TIMESTAMP NOT NULL,
    status_submissao    VARCHAR(50) NOT NULL
);

CREATE TABLE tbl_versao_submissao (
    cp_id_versao             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ce_submissao             BIGINT NOT NULL,
    nr_versao                INTEGER NOT NULL,
    tp_versao                VARCHAR(50) NOT NULL,
    dt_envio                 TIMESTAMP NOT NULL,
    ce_responsavel_envio     BIGINT NOT NULL,
    nm_arquivo               VARCHAR(255) NOT NULL,
    ds_localizacao_arquivo   VARCHAR(500) NOT NULL,
    hash_arquivo             VARCHAR(128) NOT NULL
);

-- Autoria (antes "escreve" pessoa x artigo): agora pessoa x submissão
CREATE TABLE tbl_escreve (
    ce_submissao        BIGINT NOT NULL,
    ce_pessoa           BIGINT NOT NULL,
    nr_ordem_autor      SMALLINT NOT NULL,
    in_responsavel      BOOLEAN NOT NULL,
    ce_vinculo          BIGINT,
    ce_adicionado_por   BIGINT NOT NULL,
    dt_inclusao         TIMESTAMP NOT NULL
);

CREATE TABLE tbl_topico (
    cp_id_topico   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ce_trilha      BIGINT NOT NULL,
    nm_topico      VARCHAR(150) NOT NULL,
    ds_topico      VARCHAR(1000)
);

-- Associativa submissão x tópico (ce_trilha é redundância controlada
-- para garantir, por FK composta, que o tópico é da mesma trilha)
CREATE TABLE tbl_aborda (
    ce_submissao   BIGINT NOT NULL,
    ce_topico      BIGINT NOT NULL,
    ce_trilha      BIGINT NOT NULL
);

-- Associativa pessoa x tópico com nível de expertise
CREATE TABLE tabela_imp_tem_interesse (
    ce_pessoa           BIGINT NOT NULL,
    ce_topico           BIGINT NOT NULL,
    nivel_expertise     SMALLINT NOT NULL
);

-- Substitui "recebe": revisor = membro do comitê (ce_revisor -> tbl_comite)
CREATE TABLE tbl_atribuicao_revisao (
    cp_id_atribuicao       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ce_submissao           BIGINT NOT NULL,
    ce_trilha              BIGINT NOT NULL,
    ce_revisor             BIGINT NOT NULL,
    ce_versao              BIGINT NOT NULL,
    nr_rodada              SMALLINT NOT NULL,
    dt_atribuicao          TIMESTAMP NOT NULL,
    tp_origem_atribuicao   VARCHAR(50) NOT NULL,
    status_atribuicao      VARCHAR(50) NOT NULL,
    dt_resposta            TIMESTAMP
);

CREATE TABLE tbl_revisao (
    cp_id_revisao             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ce_atribuicao             BIGINT NOT NULL,
    dt_inicio                 TIMESTAMP NOT NULL,
    dt_submissao              TIMESTAMP,
    status_revisao            VARCHAR(50) NOT NULL,
    nota_geral                SMALLINT,
    recomendacao              VARCHAR(50),
    comentario_autores        VARCHAR(4000),
    comentario_confidencial   VARCHAR(4000)
);

