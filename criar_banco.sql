ALTER TABLE tbl_instituicao          ADD CONSTRAINT pk_instituicao          PRIMARY KEY (cp_id_instituicao);
ALTER TABLE tbl_vinculo_institucional ADD CONSTRAINT pk_vinculo_institucional PRIMARY KEY (cp_id_vinculo);
ALTER TABLE tbl_evento               ADD CONSTRAINT pk_evento               PRIMARY KEY (cp_id_evento);
ALTER TABLE tbl_edicao               ADD CONSTRAINT pk_edicao               PRIMARY KEY (cp_id_edicao);
ALTER TABLE tabela_imp_se_inscreve   ADD CONSTRAINT pk_se_inscreve          PRIMARY KEY (ce_edicao, ce_pessoa);
ALTER TABLE tbl_trilha               ADD CONSTRAINT pk_trilha               PRIMARY KEY (cp_id_trilha);
ALTER TABLE tbl_comite               ADD CONSTRAINT pk_comite               PRIMARY KEY (cp_id_comite);
ALTER TABLE tbl_submissao            ADD CONSTRAINT pk_submissao            PRIMARY KEY (cp_id_submissao);
ALTER TABLE tbl_versao_submissao     ADD CONSTRAINT pk_versao_submissao     PRIMARY KEY (cp_id_versao);
