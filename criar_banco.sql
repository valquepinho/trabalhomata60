ALTER TABLE tbl_aborda
    ADD CONSTRAINT fk_aborda_topico FOREIGN KEY (ce_topico, ce_trilha)
        REFERENCES tbl_topico (cp_id_topico, ce_trilha);

ALTER TABLE tabela_imp_tem_interesse
    ADD CONSTRAINT fk_interesse_pessoa FOREIGN KEY (ce_pessoa) REFERENCES tbl_pessoa (cp_id_pessoa);
ALTER TABLE tabela_imp_tem_interesse
    ADD CONSTRAINT fk_interesse_topico FOREIGN KEY (ce_topico) REFERENCES tbl_topico (cp_id_topico);

ALTER TABLE tbl_atribuicao_revisao
