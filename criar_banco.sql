    ADD CONSTRAINT fk_escreve_adicionado_por FOREIGN KEY (ce_adicionado_por) REFERENCES tbl_pessoa (cp_id_pessoa);

ALTER TABLE tbl_topico
    ADD CONSTRAINT fk_topico_trilha FOREIGN KEY (ce_trilha) REFERENCES tbl_trilha (cp_id_trilha);

