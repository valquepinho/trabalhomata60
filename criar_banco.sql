ALTER TABLE tbl_topico               ADD CONSTRAINT pk_topico               PRIMARY KEY (cp_id_topico);
ALTER TABLE tbl_aborda               ADD CONSTRAINT pk_aborda               PRIMARY KEY (ce_submissao, ce_topico);
ALTER TABLE tabela_imp_tem_interesse ADD CONSTRAINT pk_tem_interesse        PRIMARY KEY (ce_pessoa, ce_topico);
ALTER TABLE tbl_atribuicao_revisao   ADD CONSTRAINT pk_atribuicao_revisao   PRIMARY KEY (cp_id_atribuicao);
