ALTER TABLE tbl_revisao ADD CONSTRAINT uq_revisao_atribuicao UNIQUE (ce_atribuicao);

-- 2.3 Restrições de domínio (CHECK)
ALTER TABLE tbl_pessoa ADD CONSTRAINT ck_pessoa_email CHECK (email_principal LIKE '%_@_%');
ALTER TABLE tbl_pessoa ADD CONSTRAINT ck_pessoa_orcid CHECK (cd_orcid IS NULL OR cd_orcid LIKE '____-____-____-____');
ALTER TABLE tbl_vinculo_institucional
    ADD CONSTRAINT ck_vinculo_periodo CHECK (dt_fim IS NULL OR dt_fim >= dt_inicio);
ALTER TABLE tbl_edicao ADD CONSTRAINT ck_edicao_periodo CHECK (dt_fim >= dt_inicio);
ALTER TABLE tbl_trilha
    ADD CONSTRAINT ck_trilha_anonimato CHECK (tp_anonimato IN ('SIMPLES_ANONIMO', 'DUPLO_ANONIMO', 'NAO_ANONIMO'));
ALTER TABLE tbl_trilha ADD CONSTRAINT ck_trilha_revisores CHECK (nr_revisores_desejado >= 1);
ALTER TABLE tbl_comite
    ADD CONSTRAINT ck_comite_funcao CHECK (funcao IN ('MEMBRO', 'COORDENADOR_TRILHA', 'COORDENADOR_PROGRAMA'));
ALTER TABLE tbl_comite
    ADD CONSTRAINT ck_comite_situacao CHECK (situacao IN ('CONVIDADO', 'ATIVO', 'INATIVO'));
ALTER TABLE tbl_comite ADD CONSTRAINT ck_comite_periodo CHECK (dt_fim IS NULL OR dt_fim >= dt_inicio);
ALTER TABLE tbl_submissao
    ADD CONSTRAINT ck_submissao_status CHECK (status_submissao IN
        ('REGISTRADA', 'SUBMETIDA', 'EM_REVISAO', 'ACEITA', 'REJEITADA', 'RETIRADA'));
ALTER TABLE tbl_versao_submissao ADD CONSTRAINT ck_versao_nr CHECK (nr_versao > 0);
ALTER TABLE tbl_versao_submissao
    ADD CONSTRAINT ck_versao_tipo CHECK (tp_versao IN
        ('INICIAL', 'REVISADA', 'FINAL', 'DOCUMENTO_ADICIONAL'));
ALTER TABLE tbl_escreve ADD CONSTRAINT ck_escreve_ordem CHECK (nr_ordem_autor >= 1);
ALTER TABLE tabela_imp_tem_interesse
    ADD CONSTRAINT ck_interesse_nivel CHECK (nivel_expertise BETWEEN 1 AND 5);
ALTER TABLE tbl_atribuicao_revisao ADD CONSTRAINT ck_atribuicao_rodada CHECK (nr_rodada >= 1);
ALTER TABLE tbl_atribuicao_revisao
    ADD CONSTRAINT ck_atribuicao_origem CHECK (tp_origem_atribuicao IN ('MANUAL', 'AUTOMATICA', 'IMPORTADA'));
ALTER TABLE tbl_atribuicao_revisao
    ADD CONSTRAINT ck_atribuicao_status CHECK (status_atribuicao IN
        ('PENDENTE', 'ACEITA', 'RECUSADA', 'REMOVIDA'));
ALTER TABLE tbl_atribuicao_revisao
    ADD CONSTRAINT ck_atribuicao_resposta CHECK (dt_resposta IS NULL OR dt_resposta >= dt_atribuicao);
ALTER TABLE tbl_revisao
    ADD CONSTRAINT ck_revisao_status CHECK (status_revisao IN ('EM_ANDAMENTO', 'SUBMETIDA', 'CANCELADA'));
ALTER TABLE tbl_revisao
    ADD CONSTRAINT ck_revisao_datas CHECK (dt_submissao IS NULL OR dt_submissao >= dt_inicio);
ALTER TABLE tbl_revisao
    ADD CONSTRAINT ck_revisao_submetida CHECK (status_revisao <> 'SUBMETIDA' OR dt_submissao IS NOT NULL);
ALTER TABLE tbl_revisao ADD CONSTRAINT ck_revisao_nota CHECK (nota_geral IS NULL OR nota_geral BETWEEN 1 AND 10);
ALTER TABLE tbl_revisao
    ADD CONSTRAINT ck_revisao_recomendacao CHECK (recomendacao IS NULL OR recomendacao IN
        ('ACEITAR', 'ACEITAR_COM_RESSALVAS', 'REJEITAR'));

