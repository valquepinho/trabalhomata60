-- 2.2 Unicidade (inclui as chaves candidatas usadas por FKs compostas)
ALTER TABLE tbl_pessoa ADD CONSTRAINT uq_pessoa_email UNIQUE (email_principal);
ALTER TABLE tbl_pessoa ADD CONSTRAINT uq_pessoa_orcid UNIQUE (cd_orcid);
ALTER TABLE tbl_evento ADD CONSTRAINT uq_evento_sigla UNIQUE (sg_evento);
ALTER TABLE tbl_edicao ADD CONSTRAINT uq_edicao_evento_ano UNIQUE (ce_evento, ano_edicao);
ALTER TABLE tbl_vinculo_institucional
    ADD CONSTRAINT uq_vinculo_pessoa_inst_inicio UNIQUE (ce_pessoa, ce_instituicao, dt_inicio);
ALTER TABLE tbl_trilha ADD CONSTRAINT uq_trilha_edicao_nome UNIQUE (ce_edicao, nm_trilha);
ALTER TABLE tbl_comite ADD CONSTRAINT uq_comite_trilha_pessoa_funcao UNIQUE (ce_trilha, ce_pessoa, funcao);
ALTER TABLE tbl_comite ADD CONSTRAINT uq_comite_id_trilha UNIQUE (cp_id_comite, ce_trilha);
ALTER TABLE tbl_submissao ADD CONSTRAINT uq_submissao_id_trilha UNIQUE (cp_id_submissao, ce_trilha);
